export function getTranslation(lang: Language) {
  const translationsForLang = translations[lang]
  return (key: string, params?: Record<string, string | number>): string => {
    let text = (translationsForLang as Record<string, string>)[key] || (translations['zh-CN'] as Record<string, string>)[key] || key
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        text = text.replace(`{${k}}`, String(v))
      })
    }
    return text
  }
}

export type Translation = ReturnType<typeof getTranslation>
